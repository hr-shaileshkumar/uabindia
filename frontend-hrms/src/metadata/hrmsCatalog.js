export const getHrmsSchema = (pageKey) => {
  if (!pageKey) return null;
  const key = pageKey.toLowerCase().trim();
  if (masterHrmsCatalog[key]) return masterHrmsCatalog[key];

  for (const [k, v] of Object.entries(masterHrmsCatalog)) {
    if (k.endsWith(`.${key}`) || k.replace("hrms.", "") === key) {
      return v;
    }
  }
  return null;
};
