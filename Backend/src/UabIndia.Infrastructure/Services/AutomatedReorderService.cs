using System;
using System.Collections.Generic;
using System.Linq;
using System.Threading;
using System.Threading.Tasks;
using Microsoft.EntityFrameworkCore;
using UabIndia.Application.Interfaces;
using UabIndia.Core.Entities;
using UabIndia.Infrastructure.Data;

namespace UabIndia.Infrastructure.Services
{
    public class AutomatedReorderService : IAutomatedReorderService
    {
        private readonly ApplicationDbContext _db;

        public AutomatedReorderService(ApplicationDbContext db)
        {
            _db = db;
        }

        public async Task<ReorderEvaluationResult> EvaluateAndGeneratePurchaseRequestsAsync(
            Guid tenantId,
            Guid? warehouseId = null,
            CancellationToken ct = default)
        {
            var result = new ReorderEvaluationResult();

            var itemsQuery = _db.Items.IgnoreQueryFilters()
                .Where(i => i.TenantId == tenantId && !i.IsDeleted && i.IsActive && i.ItemType == "Stockable");

            var items = await itemsQuery.ToListAsync(ct);
            result.ItemsEvaluatedCount = items.Count;

            // Find items that have active unapproved purchase requests to prevent duplicate ordering
            var pendingItemIds = await _db.PurchaseRequests.IgnoreQueryFilters()
                .Where(pr => pr.TenantId == tenantId && !pr.IsDeleted && pr.Status != "Rejected" && pr.Status != "Completed" && pr.ItemId.HasValue)
                .Select(pr => pr.ItemId!.Value)
                .ToHashSetAsync(ct);

            foreach (var item in items)
            {
                // Trigger reorder if current stock <= reorder level or min stock level
                var reorderThreshold = item.ReorderLevel > 0 ? item.ReorderLevel : item.MinStockLevel;
                if (reorderThreshold <= 0) continue;

                if (item.CurrentStock <= reorderThreshold)
                {
                    result.LowStockItemsCount++;

                    // Skip if already in purchase request pipeline
                    if (pendingItemIds.Contains(item.Id)) continue;

                    var qtyToOrder = item.ReorderQuantity > 0
                        ? item.ReorderQuantity
                        : (item.MaxStockLevel > item.CurrentStock ? item.MaxStockLevel - item.CurrentStock : 50m);

                    var requestNumber = $"PR-AUTO-{DateTime.UtcNow:yyyyMMdd}-{Guid.NewGuid():N}"[..20].ToUpperInvariant();
                    var estimatedCost = qtyToOrder * item.PurchasePrice;

                    var purchaseRequest = new PurchaseRequest
                    {
                        TenantId = tenantId,
                        CompanyId = item.CompanyId,
                        ProjectId = item.ProjectId,
                        RequestNumber = requestNumber,
                        RequestedBy = "Automated Reorder Engine",
                        Department = "Inventory Management",
                        ItemId = item.Id,
                        ItemDescription = $"{item.ItemCode} - {item.ItemName}",
                        Quantity = qtyToOrder,
                        Unit = item.UnitOfMeasure,
                        EstimatedCost = estimatedCost,
                        RequiredDate = DateTime.UtcNow.AddDays(7),
                        Justification = $"Low stock alert. Current stock ({item.CurrentStock}) is below reorder threshold ({reorderThreshold}).",
                        Status = "Draft",
                        Notes = "Generated by Automated Reorder Engine."
                    };

                    _db.PurchaseRequests.Add(purchaseRequest);
                    pendingItemIds.Add(item.Id);
                    result.PurchaseRequestsGeneratedCount++;

                    result.GeneratedRequests.Add(new ReorderPurchaseRequestSummary
                    {
                        PurchaseRequestId = purchaseRequest.Id,
                        RequestNumber = requestNumber,
                        ItemId = item.Id,
                        ItemCode = item.ItemCode,
                        ItemName = item.ItemName,
                        CurrentStock = item.CurrentStock,
                        ReorderLevel = reorderThreshold,
                        QuantityToOrder = qtyToOrder,
                        EstimatedCost = estimatedCost
                    });
                }
            }

            if (result.PurchaseRequestsGeneratedCount > 0)
            {
                await _db.SaveChangesAsync(ct);
            }

            return result;
        }
    }
}
